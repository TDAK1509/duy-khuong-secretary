export function formatNoCreditsNotice(workspaceName: string): string {
  return `Nhóm "${workspaceName}" đã hết credit. Từ bây giờ, Trợ lý không đọc ảnh, không trả lời tin nhắn và không chạy lịch của nhóm. Trợ lý vẫn giữ ảnh và tin nhắn mọi người gửi. Bạn liên hệ bên cung cấp Trợ lý để nạp thêm credit.`;
}
